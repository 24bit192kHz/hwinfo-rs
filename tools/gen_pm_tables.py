"""Generate src/sources/pm_tables.rs from ryzen_monitor_ng's pm_tables.c.

Only the facts are taken (which float index holds which field, per pm_table
version); see https://github.com/mann1x/ryzen_monitor_ng (GPL-3.0)."""
import re, sys

src = open(sys.argv[1]).read()
out = []
funcs = re.split(r'\nvoid pm_table_(0x[0-9A-Fa-f]+)\(pm_table \*pmt, void\* base_addr\) \{', src)
for i in range(1, len(funcs), 2):
    ver, body = funcs[i], funcs[i + 1].split('\n}\n')[0]
    body = re.sub(r'//.*', '', body)
    fields = {}
    meta = {}
    for m in re.finditer(r'pmt->(max_cores|max_l3|zen_version)\s*=\s*(\d+)', body):
        meta[m.group(1)] = int(m.group(2))
    for m in re.finditer(r'pmt->([A-Za-z0-9_]+)\s*=\s*pm_element\(\s*(\d+)\s*\)', body):
        fields[m.group(1)] = [int(m.group(2))]
    for m in re.finditer(r'assign_pm_elements_(2|4)\(\s*pmt->([A-Za-z0-9_]+)\s*,([^)]*)\)', body):
        fields[m.group(2)] = [int(x) for x in m.group(3).split(',')]
    for m in re.finditer(r'assign_pm_elements_(\d+)_consec\(\s*pmt->([A-Za-z0-9_]+)\s*,\s*(\d+)\s*\)', body):
        n, base = int(m.group(1)), int(m.group(3))
        fields[m.group(2)] = list(range(base, base + n))
    out.append((int(ver, 16), meta, fields))

print("// @generated by tools/gen_pm_tables.py from ryzen_monitor_ng src/pm_tables.c")
print("// (field -> f32 index per pm_table version; facts only). Do not edit.\n#![allow(dead_code)]\n")
print("pub struct Layout {\n    pub version: u32,\n    pub max_cores: usize,\n    pub max_l3: usize,\n    pub zen: u8,\n    pub fields: &'static [(&'static str, &'static [u16])],\n}\n")
print("pub static LAYOUTS: &[Layout] = &[")
for ver, meta, fields in out:
    print(f"    Layout {{ version: {ver:#08x}, max_cores: {meta.get('max_cores', 0)}, max_l3: {meta.get('max_l3', 1)}, zen: {meta.get('zen_version', 0)}, fields: &[")
    for k in sorted(fields):
        print(f'        ("{k}", &{fields[k]}),')
    print("    ] },")
print("];")
print(f"// {len(out)} layouts", file=sys.stderr)
